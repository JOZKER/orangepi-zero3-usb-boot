"""U-Boot script images and ARM64 EFI zboot extraction."""
import gzip
import hashlib
import re
import struct
import zlib

ARM64_MAGIC = b"ARM\x64"
MAX_IMAGE = 512 * 1024 * 1024

def sha256(data):
    return hashlib.sha256(data).hexdigest()

def _slice(data, start, size):
    if start < 0 or size < 0 or start + size > len(data):
        raise ValueError("Truncated kernel or invalid section bounds")
    return data[start:start + size]

def extract_image(data):
    if len(data) >= 64 and data[56:60] == ARM64_MAGIC:
        return data
    if len(data) < 64 or data[:2] != b"MZ":
        raise ValueError("Expected ARM64 Image or PE EFI zboot executable")
    pe = struct.unpack_from("<I", data, 60)[0]
    header = _slice(data, pe, 24)
    if header[:4] != b"PE\0\0" or struct.unpack_from("<H", header, 4)[0] != 0xAA64:
        raise ValueError("Expected an ARM64 PE executable")
    count = struct.unpack_from("<H", header, 6)[0]
    optional = struct.unpack_from("<H", header, 20)[0]
    linux = None
    for i in range(count):
        section = _slice(data, pe + 24 + optional + i * 40, 40)
        if section[:8].rstrip(b"\0") == b".linux":
            virtual, _, raw_size, offset = struct.unpack_from("<IIII", section, 8)
            linux = _slice(data, offset, min(virtual, raw_size))
            break
    if linux is None or len(linux) < 16 or linux[4:8] != b"zimg":
        raise ValueError("No supported .linux EFI zboot section")
    offset, size = struct.unpack_from("<II", linux, 8)
    compressed = _slice(linux, offset, size)
    if compressed.startswith(b"\x28\xb5\x2f\xfd"):
        import zstandard
        with zstandard.ZstdDecompressor().stream_reader(compressed) as reader:
            image = reader.read(MAX_IMAGE + 1)
    elif compressed.startswith(b"\x1f\x8b"):
        import io
        with gzip.GzipFile(fileobj=io.BytesIO(compressed)) as reader:
            image = reader.read(MAX_IMAGE + 1)
    else:
        raise ValueError("Unsupported EFI zboot compression")
    if len(image) > MAX_IMAGE or image[56:60] != ARM64_MAGIC:
        raise ValueError("Decompressed payload is not a bounded ARM64 Image")
    return image

def make_script(script, epoch=0):
    body = script.encode("ascii")
    payload = struct.pack(">II", len(body), 0) + body
    header = struct.pack(">7I4B32s", 0x27051956, 0, epoch, len(payload), 0, 0,
                         zlib.crc32(payload), 5, 22, 6, 0,
                         b"Orange Pi Zero 3 USB boot".ljust(32, b"\0"))
    return header[:4] + struct.pack(">I", zlib.crc32(header)) + header[8:] + payload

def read_script(data):
    if len(data) < 72:
        raise ValueError("Truncated U-Boot script")
    magic, header_crc, _, size, _, _, payload_crc = struct.unpack_from(">7I", data)
    if magic != 0x27051956 or len(data) != size + 64:
        raise ValueError("Invalid legacy image size/magic")
    if zlib.crc32(data[:4] + bytes(4) + data[8:64]) != header_crc:
        raise ValueError("Header CRC mismatch")
    payload = data[64:]
    if zlib.crc32(payload) != payload_crc:
        raise ValueError("Payload CRC mismatch")
    length, terminal = struct.unpack_from(">II", payload)
    if terminal or length != len(payload) - 8:
        raise ValueError("Invalid script component table")
    return payload[8:].decode("ascii")

def boot_command(relative, arguments, usb="0:1"):
    if not re.fullmatch(r"[A-Za-z0-9/_+.-]+", relative) or ".." in relative.split("/"):
        raise ValueError("Unsafe boot path")
    if not re.fullmatch(r"\d+:\d+", usb):
        raise ValueError("USB device must have the form 0:1")
    if not re.fullmatch(r"[A-Za-z0-9/_=,:.+ -]+", arguments):
        raise ValueError("Unsafe kernel arguments")
    return f'''# Generated by orangepi-zero3-usb-boot
echo "Booting Orange Pi Zero 3 from USB"
setenv kernel_addr_r 0x42000000
setenv fdt_addr_r 0x4fa00000
setenv ramdisk_addr_r 0x50000000
setenv bootm_low 0x40000000
setenv bootm_size 0x60000000
setenv bootargs "{arguments}"
usb start
if load usb {usb} ${{kernel_addr_r}} /{relative}/Image; then
    if load usb {usb} ${{ramdisk_addr_r}} /{relative}/initrd; then
        setenv initrd_size ${{filesize}}
        if load usb {usb} ${{fdt_addr_r}} /{relative}/zero3.dtb; then
            booti ${{kernel_addr_r}} ${{ramdisk_addr_r}}:${{initrd_size}} ${{fdt_addr_r}}
        fi
    fi
fi
echo "Boot returned; inspect the serial console"
'''
